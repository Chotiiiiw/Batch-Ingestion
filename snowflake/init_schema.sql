    SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
    BATCH_ID VARCHAR(36) NOT NULL,
    LOADED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_FACT_ORDER
        PRIMARY KEY (ORDER_KEY),
    CONSTRAINT UQ_FACT_ORDER_ID
        UNIQUE (ORDER_ID),
    CONSTRAINT FK_FACT_ORDER_CUSTOMER
        FOREIGN KEY (CUSTOMER_KEY)
        REFERENCES WAREHOUSE.DIM_CUSTOMER (CUSTOMER_KEY),
    CONSTRAINT FK_FACT_ORDER_RESTAURANT
        FOREIGN KEY (RESTAURANT_KEY)
        REFERENCES WAREHOUSE.DIM_RESTAURANT (RESTAURANT_KEY),
    CONSTRAINT FK_FACT_ORDER_DATE
        FOREIGN KEY (ORDER_DATE_KEY)
        REFERENCES WAREHOUSE.DIM_DATE (DATE_KEY),
    CONSTRAINT FK_FACT_ORDER_BATCH
        FOREIGN KEY (BATCH_ID)
        REFERENCES WAREHOUSE.ETL_BATCH (BATCH_ID),
    CONSTRAINT CK_FACT_ORDER_STATUS
        CHECK (
            ORDER_STATUS IN ('DELIVERED', 'CANCELLED', 'PREPARING')
        ),
    CONSTRAINT CK_FACT_ORDER_AMOUNTS
        CHECK (
            SUBTOTAL >= 0
            AND DISCOUNT >= 0
            AND DELIVERY_FEE >= 0
            AND TOTAL_AMOUNT >= 0
            AND TOTAL_AMOUNT = SUBTOTAL - DISCOUNT + DELIVERY_FEE
        )
);


