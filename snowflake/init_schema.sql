        AUTOINCREMENT START 1 INCREMENT 1,
    DELIVERY_ID NUMBER(38, 0) NOT NULL,
    ORDER_ID NUMBER(38, 0) NOT NULL,
    CUSTOMER_KEY NUMBER(38, 0) NOT NULL,
    RESTAURANT_KEY NUMBER(38, 0) NOT NULL,
    DRIVER_KEY NUMBER(38, 0) NOT NULL,
    ASSIGNED_DATE_KEY NUMBER(8, 0) NOT NULL,
    DELIVERY_STATUS VARCHAR(50) NOT NULL,
    DISTANCE_KM NUMBER(8, 2) NOT NULL,
    ASSIGNED_AT TIMESTAMP_TZ NOT NULL,
    PICKED_UP_AT TIMESTAMP_TZ,
    DELIVERED_AT TIMESTAMP_TZ,
    SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
    BATCH_ID VARCHAR(36) NOT NULL,
    LOADED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_FACT_DELIVERY_ATTEMPT
        PRIMARY KEY (DELIVERY_ATTEMPT_KEY),
    CONSTRAINT UQ_FACT_DELIVERY_ID
        UNIQUE (DELIVERY_ID),
    CONSTRAINT FK_FACT_DELIVERY_CUSTOMER
        FOREIGN KEY (CUSTOMER_KEY)
        REFERENCES WAREHOUSE.DIM_CUSTOMER (CUSTOMER_KEY),
    CONSTRAINT FK_FACT_DELIVERY_RESTAURANT
        FOREIGN KEY (RESTAURANT_KEY)
        REFERENCES WAREHOUSE.DIM_RESTAURANT (RESTAURANT_KEY),
    CONSTRAINT FK_FACT_DELIVERY_DRIVER
        FOREIGN KEY (DRIVER_KEY)
        REFERENCES WAREHOUSE.DIM_DRIVER (DRIVER_KEY),
    CONSTRAINT FK_FACT_DELIVERY_DATE
        FOREIGN KEY (ASSIGNED_DATE_KEY)
        REFERENCES WAREHOUSE.DIM_DATE (DATE_KEY),
    CONSTRAINT FK_FACT_DELIVERY_BATCH
        FOREIGN KEY (BATCH_ID)
        REFERENCES WAREHOUSE.ETL_BATCH (BATCH_ID),
    CONSTRAINT CK_FACT_DELIVERY_STATUS
        CHECK (
            DELIVERY_STATUS IN ('ASSIGNED', 'DELIVERED')
        ),
    CONSTRAINT CK_FACT_DELIVERY_DISTANCE
        CHECK (
            DISTANCE_KM > 0
            AND DISTANCE_KM <= 200
        ),
    CONSTRAINT CK_FACT_DELIVERY_TIMELINE
        CHECK (
            (
                PICKED_UP_AT IS NULL
                OR PICKED_UP_AT >= ASSIGNED_AT
            )
            AND
            (
                DELIVERED_AT IS NULL
                OR (
                    PICKED_UP_AT IS NOT NULL
                    AND DELIVERED_AT >= PICKED_UP_AT
                )
            )
        )
);
