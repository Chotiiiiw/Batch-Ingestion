-- ETL batch control


CREATE TABLE IF NOT EXISTS WAREHOUSE.ETL_BATCH (
    BATCH_ID VARCHAR(36) NOT NULL,
    PIPELINE_NAME VARCHAR(100) NOT NULL,
    STARTED_AT TIMESTAMP_TZ NOT NULL,
    COMPLETED_AT TIMESTAMP_TZ,
    BATCH_STATUS VARCHAR(20) NOT NULL,
    MYSQL_WATERMARK_FROM TIMESTAMP_TZ,
    MYSQL_WATERMARK_TO TIMESTAMP_TZ,
    MONGO_WATERMARK_FROM TIMESTAMP_TZ,
    MONGO_WATERMARK_TO TIMESTAMP_TZ,
    INPUT_ROW_COUNT NUMBER(38, 0) NOT NULL DEFAULT 0,
    LOADED_ROW_COUNT NUMBER(38, 0) NOT NULL DEFAULT 0,
    REJECTED_ROW_COUNT NUMBER(38, 0) NOT NULL DEFAULT 0,
    ERROR_MESSAGE VARCHAR,

    CONSTRAINT PK_ETL_BATCH
        PRIMARY KEY (BATCH_ID),
    CONSTRAINT CK_ETL_BATCH_STATUS
        CHECK (
            BATCH_STATUS IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')
        ),
    CONSTRAINT CK_ETL_BATCH_COMPLETED_AT
        CHECK (
            COMPLETED_AT IS NULL
            OR COMPLETED_AT >= STARTED_AT
        ),
    CONSTRAINT CK_ETL_BATCH_ROW_COUNTS
        CHECK (
            INPUT_ROW_COUNT >= 0
            AND LOADED_ROW_COUNT >= 0
            AND REJECTED_ROW_COUNT >= 0
            AND LOADED_ROW_COUNT + REJECTED_ROW_COUNT <= INPUT_ROW_COUNT
        )
);

