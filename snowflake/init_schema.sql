CREATE TABLE IF NOT EXISTS WAREHOUSE.DIM_DATE (
    DATE_KEY NUMBER(8, 0) NOT NULL,
    FULL_DATE DATE,
    DAY_OF_MONTH NUMBER(2, 0),
    DAY_OF_WEEK NUMBER(1, 0),
    DAY_NAME VARCHAR(20),
    WEEK_OF_YEAR NUMBER(2, 0),
    MONTH_NUMBER NUMBER(2, 0),
    MONTH_NAME VARCHAR(20),
    QUARTER_NUMBER NUMBER(1, 0),
    YEAR_NUMBER NUMBER(4, 0),
    IS_WEEKEND BOOLEAN,

    CONSTRAINT PK_DIM_DATE
        PRIMARY KEY (DATE_KEY),
    CONSTRAINT UQ_DIM_DATE_FULL_DATE
        UNIQUE (FULL_DATE),
    CONSTRAINT CK_DIM_DATE_UNKNOWN_OR_COMPLETE
        CHECK (
            (
                DATE_KEY = 0
                AND FULL_DATE IS NULL
                AND DAY_OF_MONTH IS NULL
                AND DAY_OF_WEEK IS NULL
                AND DAY_NAME IS NULL
                AND WEEK_OF_YEAR IS NULL
                AND MONTH_NUMBER IS NULL
                AND MONTH_NAME IS NULL
                AND QUARTER_NUMBER IS NULL
                AND YEAR_NUMBER IS NULL
                AND IS_WEEKEND IS NULL
            )
            OR
            (
                DATE_KEY > 0
                AND FULL_DATE IS NOT NULL
                AND DAY_OF_MONTH BETWEEN 1 AND 31
                AND DAY_OF_WEEK BETWEEN 1 AND 7
                AND DAY_NAME IS NOT NULL
                AND WEEK_OF_YEAR BETWEEN 1 AND 53
                AND MONTH_NUMBER BETWEEN 1 AND 12
                AND MONTH_NAME IS NOT NULL
                AND QUARTER_NUMBER BETWEEN 1 AND 4
                AND YEAR_NUMBER IS NOT NULL
                AND IS_WEEKEND IS NOT NULL
                AND DATE_KEY = TO_NUMBER(
                    TO_CHAR(FULL_DATE, 'YYYYMMDD')
                )
            )
        )
);


