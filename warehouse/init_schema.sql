CREATE TABLE IF NOT EXISTS dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(100),
    city VARCHAR(100) NOT NULL,
    valid_from TIMESTAMPTZ NOT NULL,
    valid_to TIMESTAMPTZ,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    hash_diff CHAR(64) NOT NULL,
    source_updated_at TIMESTAMPTZ NOT NULL,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_dim_customer_version
        UNIQUE (customer_id, valid_from),
    CONSTRAINT fk_dim_customer_batch
        FOREIGN KEY (batch_id) REFERENCES etl_batch (batch_id),
    CONSTRAINT ck_dim_customer_valid_period
        CHECK (
            (is_current AND valid_to IS NULL)
            OR
            (NOT is_current AND valid_to IS NOT NULL AND valid_to > valid_from)
        ),
    CONSTRAINT ex_dim_customer_no_overlap
        EXCLUDE USING GIST (
            customer_id WITH =,
            tstzrange(valid_from, valid_to, '[)') WITH &&
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_customer_current
    ON dim_customer (customer_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS idx_dim_customer_batch
    ON dim_customer (batch_id);


