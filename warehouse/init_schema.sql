BEGIN;

-- btree_gist lets PostgreSQL enforce non-overlapping SCD Type 2 periods for
-- BIGINT and VARCHAR source identifiers.
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;

CREATE SCHEMA IF NOT EXISTS warehouse;
SET search_path TO warehouse, public;
SET TIME ZONE 'UTC';


-- ---------------------------------------------------------------------------
-- ETL control table
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS etl_batch (
    batch_id UUID PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    batch_status VARCHAR(20) NOT NULL,
    mysql_watermark_from TIMESTAMPTZ,
    mysql_watermark_to TIMESTAMPTZ,
    mongo_watermark_from TIMESTAMPTZ,
    mongo_watermark_to TIMESTAMPTZ,
    input_row_count BIGINT NOT NULL DEFAULT 0,
    loaded_row_count BIGINT NOT NULL DEFAULT 0,
    rejected_row_count BIGINT NOT NULL DEFAULT 0,
    error_message TEXT,

    CONSTRAINT ck_etl_batch_status
        CHECK (batch_status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_etl_batch_completed_at
        CHECK (completed_at IS NULL OR completed_at >= started_at),
    CONSTRAINT ck_etl_batch_mysql_watermark
        CHECK (
            mysql_watermark_from IS NULL
            OR mysql_watermark_to IS NULL
            OR mysql_watermark_to >= mysql_watermark_from
        ),
    CONSTRAINT ck_etl_batch_mongo_watermark
        CHECK (
            mongo_watermark_from IS NULL
            OR mongo_watermark_to IS NULL
            OR mongo_watermark_to >= mongo_watermark_from
        ),
    CONSTRAINT ck_etl_batch_row_counts
        CHECK (
            input_row_count >= 0
            AND loaded_row_count >= 0
            AND rejected_row_count >= 0
            AND loaded_row_count + rejected_row_count <= input_row_count
        )
);


-- ---------------------------------------------------------------------------
-- Conformed dimensions
